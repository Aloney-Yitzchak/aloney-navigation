#!/usr/bin/env python3
"""Turns Material Symbols SVGs into Android Vector Drawables (T30).

    npm pack @material-symbols/svg-400 && tar xzf material-symbols-svg-400-*.tgz
    python docs/design/tools/material_icons.py package/outlined

Writes app/src/main/res/drawable/ic_<name>.xml for every icon in ICONS.
Material Symbols are Apache 2.0 (https://github.com/google/material-design-icons).
The icon fill is white; each layout colours it with app:tint / android:tint.
COLOURED below makes the few coloured copies.
"""

import re
import sys
from pathlib import Path

# name in the app -> Material Symbols file (outlined, weight 400; "-fill" = filled)
ICONS = {
    "search": "search", "close": "close", "arrow_forward": "arrow_forward", "arrow_back": "arrow_back",
    "chevron_left": "chevron_left", "star": "star", "star_filled": "star-fill",
    "account": "account_circle", "logo_leaf": "eco", "forest": "forest", "park": "park",
    "wifi": "wifi", "sync": "sync", "explore": "explore", "near_me": "near_me", "location_on": "location_on",
    "my_location": "my_location", "layers": "layers", "edit_location": "edit_location_alt",
    "view_in_ar": "view_in_ar", "map": "map", "staff": "manage_accounts", "shield": "verified_user",
    "schedule": "schedule", "straighten": "straighten", "walk": "directions_walk", "stairs": "stairs",
    "building": "apartment", "volume_up": "volume_up", "flash_off": "flash_off", "flash_on": "flash_on",
    "turn_left": "turn_left",
    "turn_right": "turn_right", "check_circle": "check_circle-fill", "warning": "warning", "info": "info",
    "mail": "mail", "lock": "lock", "visibility": "visibility", "logout": "logout", "login": "login",
    "save": "save", "person": "person", "notes": "sticky_note_2", "edit": "edit", "add": "add",
    "remove": "remove", "opacity": "opacity", "touch_app": "touch_app", "add_location": "add_location_alt",
    "ar_arrow": "navigation-fill", "library": "local_library", "meeting_room": "meeting_room", "school": "school", "badge": "badge",
}

# icons that point "forward" or "back": flipped automatically in right-to-left layouts
MIRRORED = {"arrow_forward", "arrow_back", "chevron_left", "walk", "logout", "login"}
# NOT mirrored: turn_left / turn_right mean a real direction, and near_me is a map pointer

# coloured copies, for places that cannot tint: layer-lists and small compound drawables
# name -> (Material Symbols file, colour, size in dp)
COLOURED = {
    "logo_leaf_green": ("eco", "@color/primary", 24),
    "walk_green": ("directions_walk", "@color/primary", 18),
}

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols "{source}" (Apache 2.0), generated by docs/design/tools/material_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="960"
    android:viewportHeight="960"{mirror}>
    <group android:translateY="960">
        <path
            android:fillColor="{colour}"
            android:pathData="{path}" />
    </group>
</vector>
"""


def main(folder):
    out = Path(__file__).resolve().parents[3] / "app/src/main/res/drawable"
    jobs = {name: (source, "@android:color/white", 24) for name, source in ICONS.items()}
    jobs.update(COLOURED)
    for name, (source, colour, size) in jobs.items():
        svg = (Path(folder) / f"{source}.svg").read_text()
        paths = re.findall(r'<path d="([^"]+)"', svg)
        mirrored = name in MIRRORED or name.rsplit("_", 1)[0] in MIRRORED
        (out / f"ic_{name}.xml").write_text(TEMPLATE.format(
            source=source, path=" ".join(paths), colour=colour, size=size,
            mirror='\n    android:autoMirrored="true"' if mirrored else ""))
    print(f"{len(jobs)} icons written to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
